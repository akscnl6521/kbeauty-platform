/**
 * 국내몰에서 제품을 등록할 때 **들어오는 자리에서 막아야 하는 것들.**
 *
 * 2026-08-08 달바·티르티르·설화수 수집에서 실제로 올라올 뻔한 것들을 막는다.
 * 스크립트 안에 있으면 테스트가 안 돼서 모듈로 뺐다 — 여기서 틀리면 화면에
 * 잘못된 가격이나 엉뚱한 유형의 제품이 뜬다.
 */

/**
 * **조건부 가격·단종 버전은 등록하지 않는다.**
 *
 * 국내몰은 같은 제품을 여러 «판매 조건» 으로 나란히 올린다. 실측 사례:
 *
 *   `[주주우대] 화이트 트러플 … 세럼 로션 100ml`   9,900원   ← 주주만 살 수 있는 값
 *   `[홈트라이 전용] 화이트 트러플 더블 세럼 앤 크림`         ← 특정 행사 참가자 전용
 *   `비타 토닝 캡슐 크림 (튜브형) - 리뉴얼 전버전`           ← 단종된 옛 버전
 *   `[미운영] 화이트 트러플 더블 세럼 앤 크림`               ← 판매 중지된 코드
 *
 * 이 값들은 **거짓이 아니지만 조건부**다. 그대로 화면에 올리면 「9,900원」 을 보고
 * 들어간 사람이 살 수 없는 값을 만난다. 우리가 지어낸 가격이 아니라도 결과는 같다.
 *
 * 판정은 **이름에 드러난 것만** 본다. 조건을 추측하지 않는다 — 이름에 표시가
 * 없으면 정상 판매로 본다.
 */
const CONDITIONAL_SALE_MARKERS: readonly RegExp[] = [
  /주주\s*우대/,
  // 2026-08-08 에이프릴스킨 실측 — 행사 조건이 상품명에 그대로 붙어 온다.
  // `[1+1]` · `[5+5 / 9,900원 특가]` 는 **2개 값**이라 단가가 아니고,
  // `[비밀할인링크]` 는 그 링크로 들어온 사람만 그 값에 산다. 같은 앰플이
  // 26,000 · 23,000 · 17,000 세 값으로 나란히 올라와 있었다.
  /\d+\s*\+\s*\d+/,
  /특가/,
  /선착순/,
  /비밀\s*(할인|특가)/,
  /한정/,
  /추가\s*할인/,
  // `[40% 역대급 할인]` — 상품명에 «할인» 이 붙으면 그 값은 행사가다.
  /\d+\s*%|할인/,
  /쿠폰/,
  /타임\s*딜|오늘\s*만/,
  // 유통기한이 임박한 재고를 따로 판다. 값이 싼 이유가 그것이라면 그대로 올릴 수 없다.
  /유통\s*기한/,
  // **묶음 값은 단가가 아니다** — `하이드라 수분 인 세럼 30ml 5개` 60,000원 은
  // 5개 값이다. 그대로 올리면 한 개에 6만원인 것처럼 보인다(2026-08-08 참존 실측).
  // 용량 뒤에 개수가 오는 형태만 본다 — 시트마스크 `10개입` 처럼 그 자체가
  // 한 상품인 경우를 잘못 막지 않기 위해서다.
  /\d+\s*(?:ml|g)\s*\d+\s*개/i,
  // `(14g)*2개` — 별표로 붙인 묶음. 위 규칙은 공백을 두는 형태만 본다.
  /\*\s*\d+\s*개/,
  // `프레쉴리 쥬스드 비타민 차징 세럼X2개` — X 로 붙인 묶음.
  /[xX×]\s*\d+\s*개/,
  // `서플 프레퍼레이션 올오버로션X2` — 개수 낱말 없이 끝에 붙는 묶음 표기.
  /[xX×]\s*\d+\s*(개|입)?\s*$/,
  // 대괄호 앞머리에 붙는 **행사 표시**. 2026-08-09 셀리맥스·카히 실측:
  // `[99딜 비밀링크]` · `[더 비타 키트 전용]` · `[쿨링썸머] … (쿨링마사저 증정)`.
  // 같은 패드가 18,900 과 43,900 두 값으로 나란히 올라와 있었다.
  /\[[^\]]*(?:딜|링크|전용|한정|이벤트|썸머|시즌|기획)[^\]]*\]/,
  // **한 상품에 용량·매수가 여럿이면 그 값이 어느 것인지 알 수 없다** —
  // `(30ml/50ml/100ml)` · `(40매/80매)` · `1매/4매/8매`.
  /\d+\s*(?:ml|g|매)\s*\/\s*\d+\s*(?:ml|g|매)/i,
  /\[\s*미운영[^\]]*\]/,
  // `[개발] 달바 시그니처 …` — 내부용 코드다. 파는 물건이 아니다.
  /\[\s*개발[^\]]*\]/,
  /내부\s*용|테스트\s*용/,
  /임직원/,
  /홈\s*트라이/,
  /체험\s*단/,
  /리뉴얼\s*전\s*버전/,
  /구\s*버전/,
  /단종/,
  /샘플/,
  /비매품/,
  /증정\s*용/,
];

/** 조건부 판매·단종이면 그 근거 문구를, 아니면 null. */
export function conditionalSaleReason(name: string): string | null {
  for (const re of CONDITIONAL_SALE_MARKERS) {
    const m = String(name ?? "").match(re);
    if (m) return m[0].replace(/\s+/g, "");
  }
  return null;
}

/**
 * **얼굴 스킨케어가 아닌 제품은 등록하지 않는다.**
 *
 * 브랜드 자사몰을 통째로 훑으면 메이크업·헤어·바디가 같이 딸려 온다. 문제는
 * 유형 추정이 이름의 «세럼» · «크림» 같은 낱말을 보기 때문에 **엉뚱한 유형으로
 * 들어온다**는 것이다. 실측:
 *
 *   `스킨 핏 커버 세럼 비비 크림`        → toner   ← BB 크림이 토너로
 *   `글로우 핏 세럼 커버 쿠션 (미니)`      → serum   ← 쿠션이 세럼으로
 *   `프로페셔널 리페어링 헤어 퍼퓸 세럼`     → serum   ← 헤어 제품이 세럼으로
 *   `화이트 트러플 세럼 바디 크림`         → serum   ← 바디 크림이 세럼으로
 *
 * `isOutsideFaceTrack` 은 **카테고리**로 거르므로 이건 못 잡는다 — 카테고리가
 * 이미 틀렸기 때문이다. 그래서 들어오는 자리에서 **이름으로** 막는다.
 *
 * 여기서 막는 것은 «얼굴 스킨케어가 아닌 것» 이다. 얼굴 제품의 유형이 틀린
 * 것(에센스를 토너로 본다든지)은 별개 문제로 다룬다.
 */
const NON_FACE_SKINCARE_MARKERS: readonly RegExp[] = [
  // 메이크업
  /메이크업/,
  /쿠션/,
  /비비\s*크림|비비크림|\bBB\b/i,
  /씨씨\s*크림|씨씨크림|\bCC\s*크림/i,
  /파운데이션/,
  /틴티드/,
  /컨실러/,
  /픽서|픽싱/,
  // `한겹 선비비` — «비비» 는 화장품 이름에서 사실상 BB 하나뿐이다.
  /선?비비/,
  /팩트/,
  /아이섀도|마스카라|아이라이너|아이브로우/,
  // 립 제품은 종류가 많다 — `너리싱 케어 립 슬리핑 팩` 처럼 «립» 뒤에 아무
  // 낱말이나 올 수 있다. 낱말 시작 자리의 «립» 만 본다.
  /(^|\s)립\s*[가-힣A-Za-z]/,
  /립스틱|립틴트|립밤|립글로스/,
  // 헤어·향수
  /헤어/,
  /샴푸/,
  /린스/,
  /퍼퓸|향수/,
  // 바디·핸드·풋
  /바디/,
  /핸드\s*크림|핸드크림/,
  /풋\s*크림|풋크림/,
  // 색조가 더 있다 — `히어로 올데이 플럼핑 틴트` · `히어로 글레이즈 립글로스`.
  /틴트/,
  /글로스/,
  /쿠션\s*팩트|팩트/,
  /수정\s*화장/,
  // 설화수 색조 — `퍼펙팅 트윈케이크`(파우더 팩트) · `퍼펙팅 스킨커버`(베이스).
  /트윈\s*케이크|트윈케이크/,
  /스킨\s*커버|스킨커버/,
  // 2026-08-08 아로마티카 실측 — 브랜드 자사몰에 **주방세제**까지 있었다.
  // 스킨케어 브랜드라고 스킨케어만 파는 게 아니다.
  /주방/,
  /세제/,
  /핸드\s*워시|핸드워시/,
  /바디\s*워시|바디워시/,
  /탈모/,
  /두피/,
  /제모|왁싱/,
  /치약|구강/,
  // `블러 스킨 파우더` 는 색조다. 다만 **효소 파우더 클렌저**처럼 세안제인
  // 파우더도 있어서, 뒤에 세안 낱말이 오면 막지 않는다.
  /파우더(?!\s*(클렌저|클렌징|워시|폼))/,
  // 호수(색상)가 여럿인 상품 — `가히 한겹 톤업 선 스킨 베이지/퍼플/그린`.
  // 색상마다 성분이 다를 수 있고, 어느 호수의 값인지도 알 수 없다.
  /(베이지|퍼플|그린|핑크|라벤더|민트|코랄|아이보리)\s*\/\s*(베이지|퍼플|그린|핑크|라벤더|민트|코랄|아이보리)/,
];

/**
 * **여러 제품을 묶어 파는 «세트» 는 등록하지 않는다.**
 *
 * 세트 상품 페이지의 전성분은 **들어 있는 제품들의 전성분을 이어 붙인 것**이다.
 * 2026-08-08 실측에서 `기미 철벽커버 2종 세트` 의 전성분이 **237개**였다 —
 * 한 제품에 그만큼 들어가지 않는다.
 *
 * 이걸 한 제품으로 등록하면 **안전 판정이 틀어진다.** 두 제품의 성분이 섞여
 * 있으니, A 에만 든 알레르겐 때문에 B 를 피하게 되거나 그 반대가 된다.
 * 「이 제품에 무엇이 들었는가」 라는 질문에 답할 수 없는 데이터다.
 *
 * `1+1` 처럼 **같은 제품 여러 개**는 세트가 아니다 — 전성분은 정상이고
 * 값만 조건부다. 그건 `conditionalSaleReason` 이 잡는다.
 */
const BUNDLE_SET_MARKERS: readonly RegExp[] = [
  /\d+\s*종\s*세트/,
  /\d+\s*종(?!\s*류)/,
  /세트/,
  /기획\s*(세트|상품)/,
  /선물\s*세트/,
  // `트러블큐어 X 짜닷 진정 패치 듀오` — 두 제품을 묶은 협업 상품.
  /듀오|콤보|패키지/,
  // `블루 드롭+블루 크림` · `메이플 에너지 인퓨징 크림+세럼` — 서로 다른 제품을
  // `+` 로 이어 붙인 이름. 숫자끼리 더한 `1+1` 은 위에서 이미 걸러진다.
  /[가-힣a-zA-Z]\s*\+\s*[가-힣a-zA-Z]/,
];

/** 여러 제품을 묶은 세트면 그 근거 문구를, 아니면 null. */
export function bundleSetReason(name: string): string | null {
  for (const re of BUNDLE_SET_MARKERS) {
    const m = String(name ?? "").match(re);
    if (m) return m[0].replace(/\s+/g, "");
  }
  return null;
}

/** 얼굴 스킨케어가 아니면 그 근거 문구를, 맞으면 null. */
export function nonFaceSkincareReason(name: string): string | null {
  for (const re of NON_FACE_SKINCARE_MARKERS) {
    const m = String(name ?? "").match(re);
    if (m) return m[0].replace(/\s+/g, "");
  }
  return null;
}

/**
 * 포장·수량 표기를 지운 **중복 비교용 키.**
 *
 * 같은 몰 안에서도 같은 제품이 두 번 올라온다 — `… 2BOX` 와 `… 2BOX (총 8개)`,
 * `퍼스널 케어 마스크` 와 `… 10개 SET`.
 *
 * **이름 유사도로 묶으면 안 된다.** 한 브랜드 라인은 이름 대부분을 공유해서
 * (달바는 거의 전부 «화이트 트러플 …») 서로 다른 제품이 통째로 묶인다. 실제로
 * 유사도 방식은 폼 클렌저·젤 클렌저·오일 클렌저를 하나로 봤다.
 *
 * **용량(ml·g)은 지우지 않는다** — 100ml 와 150ml 는 값이 다른 별개 상품이다.
 */
export function packagingNeutralKey(name: string): string {
  return String(name ?? "")
    .replace(/\d+\s*BOX/gi, " ")
    .replace(/총\s*\d+\s*개/g, " ")
    .replace(/\d+\s*개\s*(SET|세트)/gi, " ")
    .replace(/\d+\s*회분/g, " ")
    // `트러블큐어 마이크로콘 패치 (6패치)` · `(36패치)` — 같은 제품의 개수 변형이다.
    // 개수 낱말은 상품마다 다르므로(개·매·정·패치) 보이는 대로 넓혀 간다.
    .replace(/\d+\s*(패치|정|포|팩)/g, " ")
    .replace(/\(\s*\)/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}
